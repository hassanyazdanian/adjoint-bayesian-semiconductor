"""Tables 1-3 of the paper (LaTeX), generated from the result JSON files (no numbers typed by hand):
Table 1 from the tables.json of production_table.py (Example 1) and joint_report.py (Stage A), Table 2 from the
tables.json of production_table.py (Example 2), Table 3 from sensitivity.json of sensitivity_study.py.
RE and SSIM of the sampler comparisons are given in the text. Usage: python make_paper_tables.py [options]"""
import argparse, json, os
ap = argparse.ArgumentParser(description=__doc__)
ap.add_argument('--ex1', default='results/production_v1_report/ex1/tables.json')
ap.add_argument('--ex2', default='results/production_v2_report/ex2/tables.json')
ap.add_argument('--joint', default='results/production_v3_report/joint/tables.json')
ap.add_argument('--sensitivity', default='results/sensitivity_ex1/sensitivity.json')
ap.add_argument('--out', default='results/paper_tables')
A = ap.parse_args()
EX1, EX2, JNT, STU, OUT = A.ex1, A.ex2, A.joint, A.sensitivity, A.out
os.makedirs(OUT, exist_ok=True)

def i3(x): return f"{x:,.0f}".replace(",", "{,}")
def rng(v, f):
    a, b = f.format(min(v)), f.format(max(v)); return a if a == b else a + "--" + b
def pair(a, b, f): return f.format(a) + " / " + f.format(b)
def bold_ess(bulk, tail, kind):
    bu, ta = i3(bulk), i3(tail)
    return (r"\textbf{" + bu + "} / " + ta) if kind == 'bulk' else (bu + r" / \textbf{" + ta + "}")

def col_production(s):
    """pCN or NUTS column from a production tables.json stage."""
    d, c = s['diagnostics'], s['cost']; ess = d['ess']; nuts = s['method'] == 'nuts'
    fe = c['forward_equivalents']
    out = {
        'draws': f"{s['chains']} $\\times$ {i3(s['draws_per_chain'])}",
        'step': rng([x['step_size'] for x in s['sampler']], '{:.2f}') if nuts else f"$\\beta={s['sampler'][0]['beta']:.3f}$ (fixed)",
        'acc': rng([x['mean_accept_prob'] for x in s['sampler']], '{:.2f}') if nuts else f"{100*sum(x['acceptance'] for x in s['sampler'])/len(s['sampler']):.1f}\\,\\%",
        'depth': (rng([x['tree_depth_mean'] for x in s['sampler']], '{:.1f}') + f" ({max(x['tree_depth_max'] for x in s['sampler'])})") if nuts else "--",
        'div': f"{s['divergences']['count']} ({100*s['divergences']['fraction']:.2f}\\,\\%)" if nuts else "--",
        'rhat': f"{d['r_hat_max']:.3f}",
        'ess': bold_ess(d['ess_bulk_min'], d['ess_tail_min'], d['kind']),
        'grad': pair(c['adjoint']['sampling']/1e6, c['adjoint']['total']/1e6, '{:.2f}') if nuts else "--",
        'pde': pair(c['solves']['sampling']/1e6, c['solves']['total']/1e6, '{:.2f}'),
        'wall': f"{c['wall_clock_s']/60:.0f}",
        'eff': pair(1e3*ess/fe['sampling'], 1e3*ess/fe['total'], '{:.2f}'),
        'effw': f"{ess/c['wall_clock_s']:.3f}",
    }
    return out, c.get('adjoint_in_forward_equivalents')

def col_joint(s):
    d, c, sm = s['diagnostics'], s['cost'], s['sampler']; ess = d['min_ess']; fe = c['forward_equivalents']
    out = {
        'draws': f"{s['chains']} $\\times$ {i3(s['draws_per_chain'])}",
        'step': rng([x['step_size'] for x in sm], '{:.3f}'),
        'acc': rng([x['mean_accept_prob'] for x in sm], '{:.2f}'),
        'depth': rng([x['tree_depth_mean'] for x in sm], '{:.1f}') + f" ({max(x['tree_depth_max'] for x in sm)})",
        'div': f"{s['divergences']['count']} ({100*s['divergences']['fraction']:.2f}\\,\\%)",
        'rhat': f"{d['r_hat_max']:.3f}",
        'ess': bold_ess(d['ess_bulk_min'], d['ess_tail_min'], d['min_ess_kind']),
        'grad': pair(c['gradients']['sampling']/1e6, c['gradients']['total']/1e6, '{:.2f}'),
        'pde': pair(c['pde_solves']['sampling']/1e6, c['pde_solves']['total']/1e6, '{:.2f}'),
        'wall': f"{c['wall_clock_s']/60:.0f}",
        'eff': pair(1e3*ess/fe['sampling'], 1e3*ess/fe['total'], '{:.2f}'),
        'effw': f"{ess/c['wall_clock_s']:.3f}",
    }
    return out, c['lambda_adjoint_over_forward']

ROWS = [('draws', 'Retained draws'), ('step', 'Step size'), ('acc', 'Acceptance'), ('depth', 'Tree depth, mean (max.)'),
        ('div', 'Divergent transitions'), ('rhat', '$\\max\\hat R$'), ('ess', 'Min.\\ bulk / tail ESS'),
        ('grad', 'Gradients ($10^6$)'), ('pde', 'PDE solves ($10^6$)'),
        ('wall', 'Wall-clock time (min)'), ('eff', 'ESS per $10^3$ forward-eq.\\ solves'),
        ('effw', 'ESS per wall-clock second')]

def table(cols, head, caption, label, foot, src):
    spec = 'l' + 'c' * len(cols)
    body = "\n".join(lab + " & " + " & ".join(c[k] for c in cols) + r" \\" for k, lab in ROWS)
    t = (f"% generated by make_paper_tables.py from {src}; do not edit by hand\n"
         "\\begin{table}[t]\n\\centering\n\\color{blue}\n\\small\n\\setlength{\\tabcolsep}{4pt}\n"
         f"\\caption{{{caption}}}\n\\label{{{label}}}\n\\begin{{tabular}}{{{spec}}}\n\\hline\n"
         f"{head}\n\\hline\n{body}\n\\hline\n\\end{{tabular}}\n")
    if foot:
        t += f"\n\\smallskip\n\\parbox{{0.97\\linewidth}}{{\\footnotesize {foot}}}\n"
    return t + "\\end{table}\n"

T1 = json.load(open(EX1)); P1 = [s for s in T1['stages'] if s['method'] == 'pcn'][0]
N1 = [s for s in T1['stages'] if s['method'] == 'nuts' and s['target_accept_prob'] == 0.95][0]
J = json.load(open(JNT)); JA = [s for s in J['stages'] if s['stage'] in ('A', 'Stage A') or s['stage'].endswith('A')][0]
p1, _ = col_production(P1); n1, lam1 = col_production(N1); ja, lamj = col_joint(JA)
assert JA['diagnostics']['complete'] and JA['diagnostics']['r_hat_max'] < 1.01
foot1 = ("NUTS: dense mass matrix, maximum tree depth 10, target acceptance probability 0.95 (known plateaus) "
         "and 0.99 (plateau values inferred). Acceptance: mean acceptance probability (pCN) and mean acceptance "
         "statistic (NUTS). Bold: minimum ESS. Pairs $a$\\,/\\,$b$: retained draws / including warm-up and burn-in, "
         "which the ESS per wall-clock second always includes.")
t1 = table([p1, n1, ja], r" & \multicolumn{2}{c}{Known plateaus} & Plateaus inferred \\" + "\n" + r" & pCN & NUTS & NUTS \\",
           r"Sampler comparison for Example~1 (four chains each): pCN and NUTS with known plateau values, and NUTS with the plateau values inferred (Section~\ref{subsec:joint_reconstruction}).",
           "tab:ex1_sampler_comparison", foot1, f"{EX1} and {JNT} (Stage A)")

T2 = json.load(open(EX2)); P2 = [s for s in T2['stages'] if s['method'] == 'pcn'][0]
N2 = [s for s in T2['stages'] if s['method'] == 'nuts' and s['target_accept_prob'] == 0.95][0]
p2, _ = col_production(P2); n2, lam2 = col_production(N2)
t2 = table([p2, n2], r" & pCN & NUTS \\", r"Sampler comparison for Example~2 with known plateau values (four chains each); entries as in Table~\ref{tab:ex1_sampler_comparison}.",
           "tab:ex2_sampler_comparison", None, EX2)

# Table 3: sensitivity study, Example 1, known plateaus (data-generation mesh, KL truncation, sigmoid steepness k).
# Every row is taken entirely from one four-chain batch run alone on the machine, so costs and times come from the
# same batch.
import math
S = json.load(open(STU))
def sig2(x):
    s = f"{x:.2g}"
    if 'e' in s: s = f"{x:.2f}"
    if '.' not in s and len(s) == 1: s += '.0'
    return s
R = S['rows']
def row3(lab, r):
    e, dep, t = r['efficiency_per_1000_forward_equivalents'], r['depth'], r['timing']
    assert r['diagnostics_all']['passes'] and t.get('min_ess_per_wall_clock_s') is not None, r['run']
    return (f"{lab} & {r['RE']:.3f}/{r['SSIM']:.3f} & {1e3*dep['mean']:.0f}$\\pm${1e3*dep['sd']:.0f} & {r['spread']['rms_pointwise_std']:.3f} & "
            f"{sig2(e['sampling'])}/{sig2(e['total'])} & {r['sampler']['divergences']} & {t['min_ess_per_wall_clock_s']:.2f}" + r" \\")
spec = [('Ref.', R['Ref.']), ('Data 96', R['Data 96']), ('Data 384', R['Data 384']),
        ('$N_{\\mathrm{KL}}=24$', R['N_KL 24']), ('$N_{\\mathrm{KL}}=48$', R['N_KL 48']), ('$N_{\\mathrm{KL}}=96$', R['N_KL 96']),
        ('$k=10$', R['k 10']), ('$k=20$', R['k 20']), ('$k=28$', R['k 28'])]
rows3 = [row3(lab, r) for lab, r in spec]; used = [r for _, r in spec]
rh = math.ceil(max(r['diagnostics_all']['r_hat_max'] for r in used) * 1000) / 1000     # bound, rounded up
me = math.floor(min(r['diagnostics_all']['min_ess'] for r in used))                    # bound, rounded down
foot3 = (r"Ref.: data mesh 192, $N_{\mathrm{KL}}=12$, $k=14$; each other row changes one of these (Data: data-generation mesh; "
         r"the inversion mesh is $48\times48$ throughout). $10^3d$: posterior mean $\pm$ sd of the junction depth. "
         rf"All runs meet the convergence criteria ($\max\hat R\le{rh:.3f}$, minimum ESS $\ge{me}$). "
         r"ESS/$10^3$ solves: minimum ESS per $10^3$ forward-equivalent solves, retained draws / including warm-up; "
         r"ESS/s: per wall-clock second, including warm-up.")
t3 = (f"% generated by make_paper_tables.py from {STU}; do not edit by hand\n"
      "\\begin{table}[t]\n\\centering\n\\color{blue}\n\\small\n\\setlength{\\tabcolsep}{4pt}\n"
      "\\caption{Sensitivity of the Example~1 posterior (known plateaus) to the data mesh, the KL truncation and the sigmoid steepness.}\n"
      "\\label{tab:ex1_sensitivity}\n\\begin{tabular}{@{}lcccccc@{}}\n\\hline\n"
      "Run & RE/SSIM & $10^3d$ & RMS std & ESS/$10^3$ solves & Div. & ESS/s \\\\\n\\hline\n" + "\n".join(rows3) +
      "\n\\hline\n\\end{tabular}\n\n\\smallskip\n\\parbox{0.97\\linewidth}{\\footnotesize " + foot3 + "}\n\\end{table}\n")
print('Table 3 bounds', rh, me)

for name, t in (('table1_ex1.tex', t1), ('table2_ex2.tex', t2), ('table3_sensitivity.tex', t3)):
    open(os.path.join(OUT, name), 'w').write(t); print('wrote', name)
print(t1); print(t3)
